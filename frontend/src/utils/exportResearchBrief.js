/**
 * Client-side research brief exporter (Markdown download & printable PDF tear-sheet).
 */

const downloadMarkdownFile = (filename, content) => {
  const blob = new Blob([content], { type: 'text/markdown;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  setTimeout(() => URL.revokeObjectURL(url), 500);
};

const openPrintableBrief = (title, sections) => {
  const win = window.open('', '_blank', 'width=900,height=720');
  if (!win) return;
  const bodyHtml = sections
    .map(
      (sec) => `
      <section style="margin-bottom:20px;">
        <h2 style="font-size:15px;margin:0 0 8px;border-bottom:1px solid #d9e2ec;padding-bottom:4px;">${sec.heading}</h2>
        ${sec.html}
      </section>`
    )
    .join('');

  win.document.write(`<!doctype html>
<html>
<head>
  <meta charset="utf-8" />
  <title>${title}</title>
  <style>
    body { font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, sans-serif; color: #102a43; padding: 32px; max-width: 820px; margin: 0 auto; line-height: 1.5; }
    h1 { font-size: 22px; margin: 0 0 4px; }
    .meta { color: #627d98; font-size: 12px; margin-bottom: 24px; }
    table { width: 100%; border-collapse: collapse; margin-top: 8px; font-size: 13px; }
    th, td { border: 1px solid #d9e2ec; padding: 6px 10px; text-align: left; }
    th { background: #f0f4f8; }
  </style>
</head>
<body>
  <h1>${title}</h1>
  <div class="meta">Generated by NeuroStock Quantitative Platform · ${new Date().toLocaleString('en-IN')}</div>
  ${bodyHtml}
</body>
</html>`);
  win.document.close();
  win.focus();
  setTimeout(() => win.print(), 150);
};

export const exportPredictionBrief = (result, format = 'md') => {
  if (!result || !result.stock_name) return;

  const {
    stock_name: stockName,
    future_date: futureDate,
    algorithm_name: algorithmName,
    prediction_type: predictionType,
    predicted_price: predictedPrice,
    confidence_interval: ci,
    model_metrics: metrics,
    explainability,
  } = result;

  const slug = stockName.toLowerCase().replace(/[^a-z0-9]+/g, '-');

  if (format === 'pdf') {
    const sections = [
      {
        heading: 'Executive Summary',
        html: `<p><strong>Equity:</strong> ${stockName} &nbsp;|&nbsp; <strong>Model:</strong> ${algorithmName} &nbsp;|&nbsp; <strong>Target Date:</strong> ${futureDate}</p>
               <p><strong>Forecast Type:</strong> ${predictionType || 'Global Panel'} &nbsp;|&nbsp; <strong>Projected Close:</strong> INR ${predictedPrice}</p>
               ${ci ? `<p><strong>90% Confidence Band:</strong> INR ${ci.lower} – INR ${ci.upper}</p>` : ''}`,
      },
    ];

    if (explainability?.consensus) {
      const c = explainability.consensus;
      sections.push({
        heading: '7-Model Panel Consensus',
        html: `<p>Conviction: <strong>${c.label}</strong> (${c.bullish_count} Bullish vs ${c.bearish_count} Bearish, ${c.agreement_pct}% agreement)</p>`,
      });
    }

    if (explainability?.top_drivers?.length) {
      const rows = explainability.top_drivers
        .map((d) => `<tr><td>${d.label}</td><td>${d.category}</td><td>${d.impact_pct >= 0 ? '+' : ''}${d.impact_pct}%</td></tr>`)
        .join('');
      sections.push({
        heading: 'Live Factor Attribution (SHAP)',
        html: `<table><thead><tr><th>Factor</th><th>Bucket</th><th>Return Impact</th></tr></thead><tbody>${rows}</tbody></table>`,
      });
    }

    if (explainability?.term_structure?.length) {
      const rows = explainability.term_structure
        .map((t) => `<tr><td>${t.label}</td><td>INR ${t.predicted_price}</td><td>${t.predicted_return_pct >= 0 ? '+' : ''}${t.predicted_return_pct}%</td><td>INR ${t.lower_price} – ${t.upper_price}</td></tr>`)
        .join('');
      sections.push({
        heading: 'Multi-Horizon Alpha Curve',
        html: `<table><thead><tr><th>Horizon</th><th>Target</th><th>Expected Return</th><th>90% Band</th></tr></thead><tbody>${rows}</tbody></table>`,
      });
    }

    openPrintableBrief(`NeuroStock Research Brief — ${stockName}`, sections);
    return;
  }

  const lines = [
    `# NeuroStock Quantitative Research Brief: ${stockName}`,
    `- **Generated:** ${new Date().toISOString()}`,
    `- **Algorithm:** ${algorithmName}`,
    `- **Forecast Type:** ${predictionType || 'NSE 100 Global Panel'}`,
    `- **Target Date:** ${futureDate}`,
    `- **Projected Close:** ₹${predictedPrice}`,
  ];

  if (ci) {
    lines.push(`- **90% Confidence Band:** ₹${ci.lower} – ₹${ci.upper}`);
  }
  if (metrics) {
    lines.push(
      `- **Holdout Benchmarks:** DirAcc ${metrics.directional_accuracy_pct}% | MAPE ${metrics.mape_pct}% | RankIC ${metrics.rank_ic ?? 'N/A'}`
    );
  }

  if (explainability?.consensus) {
    const c = explainability.consensus;
    lines.push(
      '',
      '## 7-Model Ensemble Consensus',
      `- **Conviction:** ${c.label} (${c.bullish_count} Bullish / ${c.bearish_count} Bearish · ${c.agreement_pct}% agreement)`
    );
  }

  if (explainability?.top_drivers?.length) {
    lines.push('', '## Live Factor Attribution', '| Factor | Bucket | Impact |', '|---|---|---:|');
    explainability.top_drivers.forEach((d) => {
      lines.push(`| ${d.label} | ${d.category} | ${d.impact_pct >= 0 ? '+' : ''}${d.impact_pct}% |`);
    });
  }

  if (explainability?.term_structure?.length) {
    lines.push('', '## Multi-Horizon Alpha Term Structure', '| Horizon | Target | Return | 90% Range |', '|---|---:|---:|---:|');
    explainability.term_structure.forEach((t) => {
      lines.push(`| ${t.label} | ₹${t.predicted_price} | ${t.predicted_return_pct >= 0 ? '+' : ''}${t.predicted_return_pct}% | ₹${t.lower_price} – ₹${t.upper_price} |`);
    });
  }

  downloadMarkdownFile(`neurostock-${slug}-${futureDate || 'forecast'}.md`, lines.join('\n'));
};

export const exportPortfolioBrief = (optResult, principal, targetDate, format = 'md') => {
  if (!optResult || !optResult.allocations) return;

  if (format === 'pdf') {
    const rows = optResult.allocations
      .map(
        (a) =>
          `<tr><td>${a.name} (${a.ticker})</td><td>${a.sector}</td><td>${a.weight_pct}%</td><td>INR ${Math.round(a.allocated_inr).toLocaleString('en-IN')}</td><td>${a.expected_return_pct}%</td><td>${a.risk_contribution_pct}%</td></tr>`
      )
      .join('');
    openPrintableBrief('NeuroStock Multi-Stock Portfolio Optimization Brief', [
      {
        heading: 'Portfolio Summary',
        html: `<p><strong>Principal:</strong> INR ${Number(principal).toLocaleString('en-IN')} &nbsp;|&nbsp; <strong>Target Date:</strong> ${targetDate} &nbsp;|&nbsp; <strong>Engine:</strong> ${optResult.mode}</p>
               <p><strong>Median P50 Value:</strong> INR ${Math.round(optResult.final_value).toLocaleString('en-IN')} (${optResult.roi >= 0 ? '+' : ''}${optResult.roi}%) &nbsp;|&nbsp; <strong>Sharpe:</strong> ${optResult.sharpe_ratio} &nbsp;|&nbsp; <strong>Portfolio Vol:</strong> ${optResult.portfolio_vol_pct}%</p>`,
      },
      {
        heading: 'Optimal Capital & Risk Allocation',
        html: `<table><thead><tr><th>Equity</th><th>Sector</th><th>Weight</th><th>Capital</th><th>Exp. Return</th><th>Risk Share</th></tr></thead><tbody>${rows}</tbody></table>`,
      },
    ]);
    return;
  }

  const lines = [
    '# NeuroStock Multi-Stock Portfolio Optimization Brief',
    `- **Generated:** ${new Date().toISOString()}`,
    `- **Principal:** ₹${Number(principal).toLocaleString('en-IN')}`,
    `- **Target Date:** ${targetDate}`,
    `- **Optimization Engine:** ${optResult.mode}`,
    `- **Median (P50) Value:** ₹${Math.round(optResult.final_value).toLocaleString('en-IN')} (${optResult.roi >= 0 ? '+' : ''}${optResult.roi}% ROI)`,
    `- **Sharpe Ratio:** ${optResult.sharpe_ratio} | **Beta:** ${optResult.portfolio_beta} | **Annualized Vol:** ${optResult.portfolio_vol_pct}%`,
    `- **95% VaR / CVaR:** ₹${Math.round(optResult.var_95).toLocaleString('en-IN')} / ₹${Math.round(optResult.cvar_95).toLocaleString('en-IN')}`,
    '',
    '## Optimal Allocation & Risk Budget',
    '| Equity | Sector | Weight | Allocated (₹) | Exp. Return | Risk Share |',
    '|---|---|---:|---:|---:|---:|',
  ];

  optResult.allocations.forEach((a) => {
    lines.push(
      `| ${a.name} (${a.ticker}) | ${a.sector} | ${a.weight_pct}% | ₹${Math.round(a.allocated_inr).toLocaleString('en-IN')} | ${a.expected_return_pct}% | ${a.risk_contribution_pct}% |`
    );
  });

  if (optResult.stress_tests?.length) {
    lines.push('', '## Stress Replay Scenarios', '| Scenario | Impact | Projected Value |', '|---|---:|---:|');
    optResult.stress_tests.forEach((st) => {
      lines.push(`| ${st.scenario} | ${st.impact_pct}% | ₹${Math.round(st.projected_value).toLocaleString('en-IN')} |`);
    });
  }

  downloadMarkdownFile(`neurostock-portfolio-brief-${targetDate || 'opt'}.md`, lines.join('\n'));
};
