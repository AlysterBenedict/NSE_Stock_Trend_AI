/**
 * Client-side research brief exporter (Markdown download & XSS-safe printable PDF tear-sheet).
 */

const PRINT_STYLES = `
  body { font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, sans-serif; color: #102a43; padding: 32px; max-width: 820px; margin: 0 auto; line-height: 1.5; }
  h1 { font-size: 22px; margin: 0 0 4px; }
  .meta { color: #627d98; font-size: 12px; margin-bottom: 24px; }
  section { margin-bottom: 20px; }
  h2 { font-size: 15px; margin: 0 0 8px; border-bottom: 1px solid #d9e2ec; padding-bottom: 4px; }
  table { width: 100%; border-collapse: collapse; margin-top: 8px; font-size: 13px; }
  th, td { border: 1px solid #d9e2ec; padding: 6px 10px; text-align: left; }
  th { background: #f0f4f8; }
`;

const downloadMarkdownFile = (filename, content) => {
  const blob = new Blob([content], { type: 'text/markdown;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  setTimeout(() => URL.revokeObjectURL(url), 500);
};

/**
 * Render a declarative print document purely via safe DOM nodes + textContent (zero HTML interpolation).
 */
export const buildPrintableBriefDocument = (doc, title, sections) => {
  doc.title = String(title || 'NeuroStock Research Brief');

  if (doc.head) {
    const meta = doc.createElement('meta');
    meta.setAttribute('charset', 'utf-8');
    doc.head.appendChild(meta);

    const styleEl = doc.createElement('style');
    styleEl.textContent = PRINT_STYLES;
    doc.head.appendChild(styleEl);
  }

  const body = doc.body;
  body.innerHTML = '';

  const h1 = doc.createElement('h1');
  h1.textContent = String(title || '');
  body.appendChild(h1);

  const metaDiv = doc.createElement('div');
  metaDiv.className = 'meta';
  metaDiv.textContent = `Generated by NeuroStock Quantitative Platform · ${new Date().toLocaleString('en-IN')}`;
  body.appendChild(metaDiv);

  sections.forEach((sec) => {
    const sectionEl = doc.createElement('section');
    const h2 = doc.createElement('h2');
    h2.textContent = String(sec.heading || '');
    sectionEl.appendChild(h2);

    (sec.blocks || []).forEach((block) => {
      if (block.type === 'kv') {
        const p = doc.createElement('p');
        block.items.forEach((item, idx) => {
          if (idx > 0) {
            p.appendChild(doc.createTextNode('  |  '));
          }
          const strong = doc.createElement('strong');
          strong.textContent = `${String(item.label)}: `;
          p.appendChild(strong);
          p.appendChild(doc.createTextNode(String(item.value ?? '')));
        });
        sectionEl.appendChild(p);
      } else if (block.type === 'text') {
        const p = doc.createElement('p');
        p.textContent = String(block.text || '');
        sectionEl.appendChild(p);
      } else if (block.type === 'table') {
        const table = doc.createElement('table');
        const thead = doc.createElement('thead');
        const headRow = doc.createElement('tr');
        block.headers.forEach((hdr) => {
          const th = doc.createElement('th');
          th.textContent = String(hdr);
          headRow.appendChild(th);
        });
        thead.appendChild(headRow);
        table.appendChild(thead);

        const tbody = doc.createElement('tbody');
        block.rows.forEach((rowCells) => {
          const tr = doc.createElement('tr');
          rowCells.forEach((cell) => {
            const td = doc.createElement('td');
            td.textContent = String(cell ?? '');
            tr.appendChild(td);
          });
          tbody.appendChild(tr);
        });
        table.appendChild(tbody);
        sectionEl.appendChild(table);
      }
    });

    body.appendChild(sectionEl);
  });
};

const openPrintableBrief = (title, sections) => {
  const win = window.open('', '_blank', 'width=900,height=720');
  if (!win) return;
  try {
    win.opener = null;
  } catch {
    // Ignore read-only opener environments
  }
  buildPrintableBriefDocument(win.document, title, sections);
  win.focus();
  setTimeout(() => win.print(), 150);
};

export const exportPredictionBrief = (result, format = 'md') => {
  if (!result || !result.stock_name) return;

  const {
    stock_name: stockName,
    future_date: futureDate,
    algorithm_name: algorithmName,
    prediction_type: predictionType,
    predicted_price: predictedPrice,
    confidence_interval: ci,
    model_metrics: metrics,
    explainability,
  } = result;

  const slug = stockName.toLowerCase().replace(/[^a-z0-9]+/g, '-');

  if (format === 'pdf') {
    const summaryBlocks = [
      {
        type: 'kv',
        items: [
          { label: 'Equity', value: stockName },
          { label: 'Model', value: algorithmName },
          { label: 'Target Date', value: futureDate },
        ],
      },
      {
        type: 'kv',
        items: [
          { label: 'Forecast Type', value: predictionType || 'Global Panel' },
          { label: 'Projected Close', value: `INR ${predictedPrice}` },
        ],
      },
    ];
    if (ci) {
      summaryBlocks.push({
        type: 'kv',
        items: [{ label: '90% Confidence Band', value: `INR ${ci.lower} – INR ${ci.upper}` }],
      });
    }

    const sections = [{ heading: 'Executive Summary', blocks: summaryBlocks }];

    if (explainability?.consensus) {
      const c = explainability.consensus;
      sections.push({
        heading: '7-Model Panel Consensus',
        blocks: [
          {
            type: 'kv',
            items: [
              {
                label: 'Conviction',
                value: `${c.label} (${c.bullish_count} Bullish vs ${c.bearish_count} Bearish, ${c.agreement_pct}% agreement)`,
              },
            ],
          },
        ],
      });
    }

    if (explainability?.top_drivers?.length) {
      sections.push({
        heading: 'Live Factor Attribution (SHAP)',
        blocks: [
          {
            type: 'table',
            headers: ['Factor', 'Bucket', 'Return Impact'],
            rows: explainability.top_drivers.map((d) => [
              d.label,
              d.category,
              `${d.impact_pct >= 0 ? '+' : ''}${d.impact_pct}%`,
            ]),
          },
        ],
      });
    }

    if (explainability?.term_structure?.length) {
      sections.push({
        heading: 'Multi-Horizon Alpha Curve',
        blocks: [
          {
            type: 'table',
            headers: ['Horizon', 'Target', 'Expected Return', '90% Band'],
            rows: explainability.term_structure.map((t) => [
              t.label,
              `INR ${t.predicted_price}`,
              `${t.predicted_return_pct >= 0 ? '+' : ''}${t.predicted_return_pct}%`,
              `INR ${t.lower_price} – ${t.upper_price}`,
            ]),
          },
        ],
      });
    }

    openPrintableBrief(`NeuroStock Research Brief — ${stockName}`, sections);
    return;
  }

  const lines = [
    `# NeuroStock Quantitative Research Brief: ${stockName}`,
    `- **Generated:** ${new Date().toISOString()}`,
    `- **Algorithm:** ${algorithmName}`,
    `- **Forecast Type:** ${predictionType || 'NSE 100 Global Panel'}`,
    `- **Target Date:** ${futureDate}`,
    `- **Projected Close:** ₹${predictedPrice}`,
  ];

  if (ci) {
    lines.push(`- **90% Confidence Band:** ₹${ci.lower} – ₹${ci.upper}`);
  }
  if (metrics) {
    lines.push(
      `- **Holdout Benchmarks:** DirAcc ${metrics.directional_accuracy_pct}% | MAPE ${metrics.mape_pct}% | RankIC ${metrics.rank_ic ?? 'N/A'}`
    );
  }

  if (explainability?.consensus) {
    const c = explainability.consensus;
    lines.push(
      '',
      '## 7-Model Ensemble Consensus',
      `- **Conviction:** ${c.label} (${c.bullish_count} Bullish / ${c.bearish_count} Bearish · ${c.agreement_pct}% agreement)`
    );
  }

  if (explainability?.top_drivers?.length) {
    lines.push('', '## Live Factor Attribution', '| Factor | Bucket | Impact |', '|---|---|---:|');
    explainability.top_drivers.forEach((d) => {
      lines.push(`| ${d.label} | ${d.category} | ${d.impact_pct >= 0 ? '+' : ''}${d.impact_pct}% |`);
    });
  }

  if (explainability?.term_structure?.length) {
    lines.push('', '## Multi-Horizon Alpha Term Structure', '| Horizon | Target | Return | 90% Range |', '|---|---:|---:|---:|');
    explainability.term_structure.forEach((t) => {
      lines.push(`| ${t.label} | ₹${t.predicted_price} | ${t.predicted_return_pct >= 0 ? '+' : ''}${t.predicted_return_pct}% | ₹${t.lower_price} – ₹${t.upper_price} |`);
    });
  }

  downloadMarkdownFile(`neurostock-${slug}-${futureDate || 'forecast'}.md`, lines.join('\n'));
};

export const exportPortfolioBrief = (optResult, principal, targetDate, format = 'md') => {
  if (!optResult || !optResult.allocations) return;

  if (format === 'pdf') {
    openPrintableBrief('NeuroStock Multi-Stock Portfolio Optimization Brief', [
      {
        heading: 'Portfolio Summary',
        blocks: [
          {
            type: 'kv',
            items: [
              { label: 'Principal', value: `INR ${Number(principal).toLocaleString('en-IN')}` },
              { label: 'Target Date', value: targetDate },
              { label: 'Engine', value: optResult.mode },
            ],
          },
          {
            type: 'kv',
            items: [
              {
                label: 'Median P50 Value',
                value: `INR ${Math.round(optResult.final_value).toLocaleString('en-IN')} (${optResult.roi >= 0 ? '+' : ''}${optResult.roi}%)`,
              },
              { label: 'Sharpe', value: optResult.sharpe_ratio },
              { label: 'Portfolio Vol', value: `${optResult.portfolio_vol_pct}%` },
            ],
          },
        ],
      },
      {
        heading: 'Optimal Capital & Risk Allocation',
        blocks: [
          {
            type: 'table',
            headers: ['Equity', 'Sector', 'Weight', 'Capital', 'Exp. Return', 'Risk Share'],
            rows: optResult.allocations.map((a) => [
              `${a.name} (${a.ticker})`,
              a.sector,
              `${a.weight_pct}%`,
              `INR ${Math.round(a.allocated_inr).toLocaleString('en-IN')}`,
              `${a.expected_return_pct}%`,
              `${a.risk_contribution_pct}%`,
            ]),
          },
        ],
      },
    ]);
    return;
  }

  const lines = [
    '# NeuroStock Multi-Stock Portfolio Optimization Brief',
    `- **Generated:** ${new Date().toISOString()}`,
    `- **Principal:** ₹${Number(principal).toLocaleString('en-IN')}`,
    `- **Target Date:** ${targetDate}`,
    `- **Optimization Engine:** ${optResult.mode}`,
    `- **Median (P50) Value:** ₹${Math.round(optResult.final_value).toLocaleString('en-IN')} (${optResult.roi >= 0 ? '+' : ''}${optResult.roi}% ROI)`,
    `- **Sharpe Ratio:** ${optResult.sharpe_ratio} | **Beta:** ${optResult.portfolio_beta} | **Annualized Vol:** ${optResult.portfolio_vol_pct}%`,
    `- **95% VaR / CVaR:** ₹${Math.round(optResult.var_95).toLocaleString('en-IN')} / ₹${Math.round(optResult.cvar_95).toLocaleString('en-IN')}`,
    '',
    '## Optimal Allocation & Risk Budget',
    '| Equity | Sector | Weight | Allocated (₹) | Exp. Return | Risk Share |',
    '|---|---|---:|---:|---:|---:|',
  ];

  optResult.allocations.forEach((a) => {
    lines.push(
      `| ${a.name} (${a.ticker}) | ${a.sector} | ${a.weight_pct}% | ₹${Math.round(a.allocated_inr).toLocaleString('en-IN')} | ${a.expected_return_pct}% | ${a.risk_contribution_pct}% |`
    );
  });

  if (optResult.stress_tests?.length) {
    lines.push('', '## Stress Replay Scenarios', '| Scenario | Impact | Projected Value |', '|---|---:|---:|');
    optResult.stress_tests.forEach((st) => {
      lines.push(`| ${st.scenario} | ${st.impact_pct}% | ₹${Math.round(st.projected_value).toLocaleString('en-IN')} |`);
    });
  }

  downloadMarkdownFile(`neurostock-portfolio-brief-${targetDate || 'opt'}.md`, lines.join('\n'));
};
